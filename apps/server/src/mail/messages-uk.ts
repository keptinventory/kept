// AI caps (D206): the cap in words, and how much of it is used.
function ukCapOf(c: AiCapFacts): string {
  switch (c.scope) {
    case 'location':
      return `ліміт ШІ для «${c.target}»`;
    case 'member':
      return c.target ? `ліміт ШІ для ${c.target}` : `ліміт ШІ учасника`;
    case 'account':
      return `ліміт ШІ вашого облікового запису`;
    case 'user':
      return `ваш особистий ліміт ШІ`;
    case 'instance':
      return `ліміт ШІ цього сервера`;
    case 'instance_account':
      return c.target
        ? `квота ${c.target} на ключі ШІ цього сервера`
        : `квота на ключі ШІ цього сервера`;
  }
}
const ukUsed = (c: AiCapFacts) =>
  c.unit === 'money'
    ? `${c.currency} ${c.used} із ${c.currency} ${c.limit}`
    : `токенів: ${tokens('uk', c.used)} із ${tokens('uk', c.limit)}`;

function ukCap(level: 80 | 100, c: AiCapFacts, ctx: MessageContext, footnote: string): Message {
  const cap = ukCapOf(c);
  if (level === 80) {
    return {
      subject: `Kept: ${cap}: використано 80% цього місяця`,
      paragraphs: [
        `${capitalise(cap)}: ${ukUsed(c)} із початку місяця.`,
        'Коли ліміт буде досягнуто, ШІ призупиниться до 1-го числа наступного місяця. Сканування й далі зберігаються, а їхні фото буде прочитано після відновлення ШІ.',
      ],
      action: { label: 'Відкрити налаштування ШІ', url: aiPage(ctx, c.scope) },
      footnote,
    };
  }
  return {
    subject: `Kept: ШІ призупинено до ${day(c.pausedUntil)}`,
    paragraphs: [
      `${capitalise(cap)}: вичерпано, ${ukUsed(c)} цього місяця.`,
      `ШІ призупинено до ${day(c.pausedUntil)}. Сканування й далі зберігаються, а їхні фото буде прочитано після відновлення. Щоб відновити раніше, збільшіть або приберіть ліміт.`,
    ],
    action: { label: 'Відновити зараз', url: aiPage(ctx, c.scope) },
    footnote,
  };
}

