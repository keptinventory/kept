// How many, with the noun in the form the number asks for (1, 2 to 4, 5 or more).
const ukCount = (n: number, one: string, few: string, many: string) => {
  const form = new Intl.PluralRules('uk').select(n);
  return `${n} ${form === 'one' ? one : form === 'few' ? few : many}`;
};

